/**
 * npm run images
 *
 * Turns the photos you download into fast WebP files and links them to products.
 *
 *   1. Put photos in   public/products/<product-slug>/front.jpg   (and back.jpg, detail.jpg ...)
 *   2. Run             npm run images
 *   3. Output goes to  public/products/<product-slug>/web/front.webp
 *      and the links are written to src/data/product-images.generated.ts
 *
 * Products without a photo keep their current image automatically.
 *
 * Options:
 *   --init    create an empty folder for every product (so you only drop files in)
 *   --force   re-convert every photo, even ones that are up to date
 *   --check   only report what is there and what is missing; change nothing
 */
import { existsSync, mkdirSync, readdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { PRODUCTS } from '../src/data/catalog';

const ROOT = path.resolve(import.meta.dirname, '..');
const PHOTO_DIR = path.join(ROOT, 'public', 'products');
const MANIFEST_FILE = path.join(ROOT, 'src', 'data', 'product-images.generated.ts');
const OUTPUT_SUBDIR = 'web';

const MAX_WIDTH = 1200;
const MAX_HEIGHT = 1600;
const WEBP_QUALITY = 82;
const MIN_GOOD_SIZE = 800; // warn below this many pixels on the shorter side

const SOURCE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);
/** Accepted file names (before the extension). */
const NAME_PATTERN = /^(front|back|detail(-\d+)?|gallery-\d+)$/;

const args = new Set(process.argv.slice(2));
const FORCE = args.has('--force');
const CHECK_ONLY = args.has('--check');

type Role = 'front' | 'back' | 'detail' | 'gallery';
interface Source {
  name: string; // e.g. "front", "detail-2"
  role: Role;
  file: string; // absolute path
}
interface ManifestEntry {
  front?: string;
  back?: string;
  gallery?: string[];
  details?: string[];
}

const productSlugs = new Set(PRODUCTS.map((p) => p.slug));
const warnings: string[] = [];

function roleOf(name: string): Role {
  if (name === 'front' || name === 'back') return name;
  return name.startsWith('detail') ? 'detail' : 'gallery';
}

/** "Front.JPG", "front.jpg.jpg" and "front.jpeg" all count as "front". */
function findSources(folder: string): Source[] {
  const byName = new Map<string, Source>();
  for (const entry of readdirSync(folder)) {
    const full = path.join(folder, entry);
    if (!statSync(full).isFile()) continue;
    const ext = path.extname(entry).toLowerCase();
    if (!SOURCE_EXT.has(ext)) continue;
    const name = entry.split('.')[0].trim().toLowerCase();
    if (!NAME_PATTERN.test(name)) {
      warnings.push(`${path.relative(ROOT, full)}: unknown file name. Use front, back, detail, detail-2 or gallery-1.`);
      continue;
    }
    if (byName.has(name)) {
      warnings.push(`${path.relative(ROOT, full)}: two files named "${name}". Keeping ${path.basename(byName.get(name)!.file)}.`);
      continue;
    }
    byName.set(name, { name, role: roleOf(name), file: full });
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
}

/** Closest product slug, to catch typos in folder names. */
function suggestSlug(folder: string): string | undefined {
  const words = new Set(folder.split('-'));
  let best: { slug: string; score: number } | undefined;
  for (const slug of productSlugs) {
    const parts = slug.split('-');
    const score = parts.filter((w) => words.has(w)).length / Math.max(parts.length, words.size);
    if (!best || score > best.score) best = { slug, score };
  }
  return best && best.score >= 0.4 ? best.slug : undefined;
}

async function convert(source: Source, outFile: string): Promise<void> {
  const upToDate = existsSync(outFile) && statSync(outFile).mtimeMs >= statSync(source.file).mtimeMs;
  const meta = await sharp(source.file).metadata();
  const shortSide = Math.min(meta.width ?? 0, meta.height ?? 0);
  if (shortSide && shortSide < MIN_GOOD_SIZE) {
    warnings.push(
      `${path.relative(ROOT, source.file)}: only ${meta.width}×${meta.height}px. Look for a bigger photo (at least ${MIN_GOOD_SIZE}px).`,
    );
  }
  if (CHECK_ONLY || (upToDate && !FORCE)) return;
  await sharp(source.file)
    .rotate() // respect phone/camera orientation
    .resize({ width: MAX_WIDTH, height: MAX_HEIGHT, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: WEBP_QUALITY, effort: 5 })
    .toFile(outFile);
}

function writeManifest(manifest: Record<string, ManifestEntry>): void {
  const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
  const body = JSON.stringify(sorted, null, 2);
  writeFileSync(
    MANIFEST_FILE,
    `// Generated by \`npm run images\`. Do not edit by hand.
// Maps product slug -> real photo paths under /products/<slug>/${OUTPUT_SUBDIR}/.
import type { ProductImageManifest } from '../lib/product-attributes';

export const PRODUCT_IMAGE_MANIFEST: ProductImageManifest = ${body};
`,
  );
}

function initFolders(): void {
  mkdirSync(PHOTO_DIR, { recursive: true });
  let created = 0;
  for (const slug of productSlugs) {
    const dir = path.join(PHOTO_DIR, slug);
    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
      created += 1;
    }
  }
  console.log(`Created ${created} product folders in public/products/ (${productSlugs.size} products in total).`);
}

async function main(): Promise<void> {
  if (args.has('--init')) {
    initFolders();
    return;
  }
  if (!existsSync(PHOTO_DIR)) {
    console.log('No public/products folder yet. Run "npm run images -- --init" to create one folder per product.');
    if (!CHECK_ONLY) writeManifest({});
    return;
  }

  const manifest: Record<string, ManifestEntry> = {};
  let converted = 0;

  for (const folder of readdirSync(PHOTO_DIR).sort()) {
    const dir = path.join(PHOTO_DIR, folder);
    if (!statSync(dir).isDirectory()) continue;
    if (!productSlugs.has(folder)) {
      const hint = suggestSlug(folder);
      warnings.push(`public/products/${folder}: no product has this slug.${hint ? ` Did you mean "${hint}"?` : ''}`);
      continue;
    }

    const sources = findSources(dir);
    const outDir = path.join(dir, OUTPUT_SUBDIR);
    if (sources.length && !CHECK_ONLY) mkdirSync(outDir, { recursive: true });

    const entry: ManifestEntry = {};
    for (const source of sources) {
      const outFile = path.join(outDir, `${source.name}.webp`);
      const before = existsSync(outFile) ? statSync(outFile).mtimeMs : 0;
      await convert(source, outFile);
      if (!CHECK_ONLY && existsSync(outFile) && statSync(outFile).mtimeMs !== before) converted += 1;

      const url = `/products/${folder}/${OUTPUT_SUBDIR}/${source.name}.webp`;
      if (source.role === 'front') entry.front = url;
      else if (source.role === 'back') entry.back = url;
      else if (source.role === 'detail') (entry.details ??= []).push(url);
      else (entry.gallery ??= []).push(url);
    }

    // Remove converted files whose original photo was deleted.
    if (!CHECK_ONLY && existsSync(outDir)) {
      const keep = new Set(sources.map((s) => `${s.name}.webp`));
      for (const file of readdirSync(outDir)) {
        if (file.endsWith('.webp') && !keep.has(file)) unlinkSync(path.join(outDir, file));
      }
    }

    if (sources.length && !entry.front) {
      warnings.push(`public/products/${folder}: has photos but no front.jpg. The current image is used as the front.`);
    }
    if (Object.keys(entry).length) manifest[folder] = entry;
  }

  if (!CHECK_ONLY) writeManifest(manifest);
  report(manifest, converted);
}

function report(manifest: Record<string, ManifestEntry>, converted: number): void {
  const needsBack = PRODUCTS.filter((p) => p.category === 'jerseys' || p.category === 'f1');
  const fronts = PRODUCTS.filter((p) => manifest[p.slug]?.front).length;
  const backs = needsBack.filter((p) => manifest[p.slug]?.back).length;

  console.log('');
  console.log(CHECK_ONLY ? 'Photo check (nothing changed)' : `Converted ${converted} photo(s) to WebP.`);
  console.log(`  Front photos: ${fronts} of ${PRODUCTS.length} products`);
  console.log(`  Back photos:  ${backs} of ${needsBack.length} jerseys and F1 items`);

  const missingBack = needsBack.filter((p) => manifest[p.slug]?.front && !manifest[p.slug]?.back);
  if (missingBack.length) {
    console.log('\nHave a front but no back yet:');
    for (const p of missingBack) console.log(`  - ${p.slug}`);
  }
  if (warnings.length) {
    console.log(`\n${warnings.length} warning(s):`);
    for (const w of warnings) console.log(`  ! ${w}`);
  }
  if (!CHECK_ONLY) console.log('\nLinks written to src/data/product-images.generated.ts. Restart "npm run dev" if it is running.');
}

main().catch((error) => {
  console.error('Image script failed:', error instanceof Error ? error.message : error);
  process.exit(1);
});
