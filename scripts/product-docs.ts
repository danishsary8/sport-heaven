/**
 * npm run images:docs
 *
 * Writes two checklists from the live catalog (re-run any time; progress updates):
 *   docs/product-images-checklist.md  - every product, its folder, the photos needed and Google search links
 *   docs/product-details-review.md    - facts set for each kit and what still needs checking
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PRODUCTS } from '../src/data/catalog';
import { getKitDetails, isShowable, type Fact } from '../src/data/kit-details';
import type { Product, ProductCategory } from '../src/types/store';

const ROOT = path.resolve(import.meta.dirname, '..');
const DOCS = path.join(ROOT, 'docs');
const PHOTO_DIR = path.join(ROOT, 'public', 'products');

const SECTIONS: Array<{ category: ProductCategory; title: string }> = [
  { category: 'jerseys', title: 'Jerseys' },
  { category: 'f1', title: 'F1 team wear' },
  { category: 'boots', title: 'Boots' },
  { category: 'balls', title: 'Balls' },
  { category: 'essentials', title: 'Goalkeeper & gear' },
];

const needsBack = (p: Product) => p.category === 'jerseys' || p.category === 'f1';
const team = (p: Product) => (p.club ?? '').replace(/\s+National Team$/i, '');

/** Which photo files exist (any image extension, any letter case). */
function photosFor(slug: string): Set<string> {
  const dir = path.join(PHOTO_DIR, slug);
  if (!existsSync(dir)) return new Set();
  return new Set(
    readdirSync(dir)
      .filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f))
      .map((f) => f.split('.')[0].toLowerCase()),
  );
}

/** Search words without colours: team + season + kit type + garment. */
function searchPhrase(p: Product): string {
  if (p.category === 'jerseys') {
    const kit = p.kitType === 'Special' ? 'special edition' : (p.kitType ?? 'home').toLowerCase();
    return `${team(p)} ${p.season} ${kit} ${p.isRetro ? 'retro jersey' : 'jersey'}`;
  }
  if (p.category === 'f1') {
    const what = p.garmentType === 'jacket' ? 'team jacket' : p.name.includes('Special') ? 'special edition jersey' : 'team jersey';
    return `${team(p)} ${p.season} ${what}`;
  }
  return p.name;
}

function googleImages(query: string): string {
  return `https://www.google.com/search?tbm=isch&q=${encodeURIComponent(query)}`;
}

function queries(p: Product): { front: string; back?: string; detail: string } {
  const phrase = searchPhrase(p);
  if (needsBack(p)) {
    return {
      front: `${phrase} front official`,
      back: `${phrase} back official`,
      detail: `${phrase} crest close up`,
    };
  }
  if (p.category === 'boots') {
    return { front: `${phrase} side view official`, detail: `${phrase} soleplate` };
  }
  return { front: `${phrase} official product photo`, detail: `${phrase} close up` };
}

function status(p: Product, have: Set<string>): string {
  const front = have.has('front');
  if (!needsBack(p)) return front ? '✅ done' : '⬜ front';
  const back = have.has('back');
  if (front && back) return '✅ done';
  if (front) return '🟨 back missing';
  if (back) return '🟨 front missing';
  return '⬜ front + back';
}

function imagesChecklist(): string {
  const all = PRODUCTS.map((p) => ({ p, have: photosFor(p.slug) }));
  const done = all.filter(({ p, have }) => status(p, have).startsWith('✅')).length;
  const kits = all.filter(({ p }) => needsBack(p));
  const backs = kits.filter(({ have }) => have.has('back')).length;

  const lines: string[] = [
    '# Product photo checklist',
    '',
    '> Generated by `npm run images:docs` from the catalog. Re-run it to update the status column.',
    '',
    `**Progress:** ${done} of ${all.length} products complete · back photos ${backs} of ${kits.length} jerseys and F1 items.`,
    '',
    '## How to add photos',
    '',
    '1. Create one empty folder per product (only once):',
    '',
    '   ```bash',
    '   npm run images -- --init',
    '   ```',
    '',
    '2. Click a search link below. In Google Images use **Tools → Size → Large**.',
    '3. Save the photo into the product folder with the exact file name:',
    '   - `front.jpg`: the front of the shirt (for boots: side view)',
    '   - `back.jpg`: the back of the shirt (jerseys and F1)',
    '   - `detail.jpg`, `detail-2.jpg`: optional close-ups (crest, fabric, sole plate)',
    '   - `gallery-1.jpg`, `gallery-2.jpg`: optional extra photos',
    '4. Convert and link everything:',
    '',
    '   ```bash',
    '   npm run images',
    '   ```',
    '',
    '## Rules for a good photo',
    '',
    '- At least **1000 px** on the short side (the script warns below 800 px).',
    '- Plain light background, whole shirt visible, no model, no watermark.',
    '- Front and back from the **same source**, so size and light match.',
    '- Prefer the official club store or the brand site (Nike, Adidas, Puma).',
    '- `.jpg`, `.png`, `.webp` and `.avif` all work; letter case does not matter (`Front.JPG` is fine).',
    '- Brand photos are OK for this portfolio demo with the footer credit. For a real shop, replace them with your own or licensed photos.',
    '',
  ];

  for (const section of SECTIONS) {
    const items = all.filter(({ p }) => p.category === section.category);
    if (!items.length) continue;
    const withBack = needsBack(items[0].p);
    lines.push(`## ${section.title} (${items.length})`, '');
    lines.push(
      withBack
        ? '| Status | Product | Folder (`public/products/…`) | Front search | Back search | Detail (optional) |'
        : '| Status | Product | Folder (`public/products/…`) | Front search | Detail (optional) |',
    );
    lines.push(withBack ? '|---|---|---|---|---|---|' : '|---|---|---|---|---|');
    for (const { p, have } of items) {
      const q = queries(p);
      const cells = [
        status(p, have),
        p.name,
        `\`${p.slug}\``,
        `[${q.front}](${googleImages(q.front)})`,
        ...(withBack && q.back ? [`[${q.back}](${googleImages(q.back)})`] : []),
        `[close-up](${googleImages(q.detail)})`,
      ];
      lines.push(`| ${cells.join(' | ')} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function fact(f: Fact<string | null> | undefined, empty = '-'): string {
  if (!f) return empty;
  const value = f.value ?? 'None';
  if (f.confidence === 'confirmed') return value;
  if (f.confidence === 'likely') return `${value} (likely)`;
  return `❓ ${f.value ?? 'unknown'}`;
}

function detailsReview(): string {
  const kits = PRODUCTS.filter(needsBack);
  const open = kits.filter((p) => (getKitDetails(p)?.notes.length ?? 0) > 0).length;
  const lines: string[] = [
    '# Product details review',
    '',
    '> Generated by `npm run images:docs`. Facts live in `src/data/kit-details.ts`.',
    '',
    'How to read this:',
    '',
    '- **plain value**: confirmed, long-running fact.',
    '- **(likely)**: announced deal or brand naming pattern; check it is current for this season.',
    '- **❓**: not confirmed. It is **hidden from shoppers** until you confirm it in `kit-details.ts`.',
    '',
    'Fabric rule used for every kit (confirmed brand practice):',
    '',
    '| Brand | Fan version | Player version |',
    '|---|---|---|',
    '| Nike | Stadium, Dri-FIT | Match, Dri-FIT ADV |',
    '| Adidas | Replica, AEROREADY | Authentic, HEAT.RDY |',
    '| Puma | Replica, dryCELL | Authentic, ULTRAWEAVE |',
    '',
    'National team kits are named by tournament year ("2026" = World Cup 2026), so their season is `2026`, not `2026/27`.',
    '',
    `**${open} of ${kits.length} items have something to check.**`,
    '',
    '| Product | Supplier | Front sponsor | Brand name (Fan) | Brand name (Player) | To check |',
    '|---|---|---|---|---|---|',
  ];
  for (const p of kits) {
    const d = getKitDetails(p)!;
    const player = p.versions?.includes('Player') ? fact(d.playerName) : 'Fan only';
    const notes = d.notes.length ? d.notes.join('<br>') : '✅ nothing';
    lines.push(
      `| ${p.name} | ${fact(d.supplier)} | ${p.category === 'f1' ? 'n/a' : fact(d.sponsor)} | ${fact(d.fanName)} | ${player} | ${notes} |`,
    );
  }
  lines.push(
    '',
    '## Shown to shoppers',
    '',
    'For each kit the product page shows: kit supplier, front sponsor, fabric for Fan and Player version, fit, and the brand-style names, but only facts that are not marked ❓.',
    `Hidden right now: ${kits.filter((p) => { const d = getKitDetails(p)!; return !isShowable(d.supplier) || (d.sponsor && !isShowable(d.sponsor)); }).length} items have at least one hidden fact.`,
    '',
  );
  return lines.join('\n');
}

mkdirSync(DOCS, { recursive: true });
writeFileSync(path.join(DOCS, 'product-images-checklist.md'), imagesChecklist());
writeFileSync(path.join(DOCS, 'product-details-review.md'), detailsReview());
console.log('Wrote docs/product-images-checklist.md and docs/product-details-review.md');
